import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = import.meta.dir;
const FRONTEND_DIR = join(ROOT, 'frontend');
const DIST_SPA_DIR = join(ROOT, 'dist-spa');
const GENERATED_MANIFEST = join(ROOT, 'server', 'static-assets.gen.ts');
const OUT_DIR = join(ROOT, 'dist');

async function buildFrontend() {
  console.log('Building frontend (vite build)...');
  const result = Bun.spawnSync(['pnpm', 'run', 'build'], {
    cwd: FRONTEND_DIR,
    stdio: ['inherit', 'inherit', 'inherit'],
  });
  if (result.exitCode !== 0) {
    throw new Error(`Frontend build failed with exit code ${result.exitCode}`);
  }
}

async function generateStaticAssetsManifest() {
  console.log('Generating embedded asset manifest...');
  const glob = new Bun.Glob('**/*');
  const files: string[] = [];
  for await (const path of glob.scan({ cwd: DIST_SPA_DIR, onlyFiles: true })) {
    files.push(path);
  }

  if (files.length === 0) {
    throw new Error(`No files found in ${DIST_SPA_DIR} — did the frontend build run?`);
  }

  const importLines: string[] = [];
  const entryLines: string[] = [];

  files.forEach((relPath, index) => {
    const importName = `asset_${index}`;
    const fileRelativeFromServer = relative(join(ROOT, 'server'), join(DIST_SPA_DIR, relPath))
      .split('\\')
      .join('/');
    const urlPath = `/${relPath.split('\\').join('/')}`;

    importLines.push(
      `import ${importName} from "${fileRelativeFromServer}" with { type: "file" };`,
    );
    entryLines.push(`  "${urlPath}": Bun.file(${importName}),`);
  });

  const contents = `// Auto-generated by build.ts — do not edit by hand.
${importLines.join('\n')}

const manifest: Record<string, Bun.BunFile> = {
${entryLines.join('\n')}
};

export default manifest;
`;

  await writeFile(GENERATED_MANIFEST, contents, 'utf8');
}

async function compileExecutable() {
  console.log('Compiling standalone executable...');
  await mkdir(OUT_DIR, { recursive: true });

  const outfile =
    process.platform === 'win32'
      ? join(OUT_DIR, 'ifs-bruno-ui.exe')
      : join(OUT_DIR, 'ifs-bruno-ui');

  const result = await Bun.build({
    entrypoints: [join(ROOT, 'server', 'index.ts')],
    compile: {
      outfile,
      windows: {
        title: 'ifs-bruno-ui',
        hideConsole: false,
      },
    },
  });

  if (!result.success) {
    for (const message of result.logs) console.error(message);
    throw new Error('Compilation failed');
  }

  console.log(`Executable written to ${outfile}`);
}

async function cleanupGeneratedManifest() {
  await rm(GENERATED_MANIFEST, { force: true });
}

try {
  await buildFrontend();
  await generateStaticAssetsManifest();
  await compileExecutable();
} finally {
  await cleanupGeneratedManifest();
}
